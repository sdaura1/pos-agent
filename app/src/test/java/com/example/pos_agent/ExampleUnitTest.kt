package com.example.pos_agent

import org.junit.Assert.assertEquals
import org.junit.Test

class ExampleUnitTest {

    @Test
    fun `addition should return four when adding two and two`() {
        // Arrange
        val left = 2
        val right = 2

        // Act
        val sum = left + right

        // Assert
        assertEquals(4, sum)
    }
}
